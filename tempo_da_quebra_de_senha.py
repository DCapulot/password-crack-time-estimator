    senha = input("\n➤ Digite a senha que quer testar: ")
    tentativas_por_segundo = escolher_cenario()

    r = estimar_tempo_quebra(senha, tentativas_por_segundo)
    forca = classificar_forca(r["entropia_bits"])
    tipos = mostrar_tipos_de_caractere(senha)

    print("\n" + "-" * 60)
    print("RESULTADO")
